r"""
打包进度模型深度测试: 阶段表、单调性、段内语义、快照契约。
进度必须可解释, 禁止回退, 构建权重应占主导。
"""

from __future__ import annotations


def test_阶段表连续覆盖0到1(打包模块) -> None:
    表 = 打包模块.阶段表
    assert 表[0][1] == 0.0
    assert 表[-1][2] == 1.0
    for i in range(len(表) - 1):
        _k1, _a1, 止1, _n1 = 表[i]
        _k2, 起2, _b2, _n2 = 表[i + 1]
        assert 止1 == 起2, f"阶段缝隙/重叠: {止1} vs {起2}"


def test_构建阶段权重占主导(打包模块) -> None:
    权重 = {键: 止 - 起 for 键, 起, 止, _ in 打包模块.阶段表}
    assert 权重["构建"] == max(权重.values())
    assert 权重["构建"] >= 0.5
    assert 权重["版本"] + 权重["依赖"] < 权重["构建"]


def test_查阶段边界(打包模块) -> None:
    序, 键, 起, 止, 名 = 打包模块.查阶段(0.0)
    assert 键 == "版本" and 序 == 1
    序, 键, 起, 止, 名 = 打包模块.查阶段(0.149)
    assert 键 == "依赖"
    序, 键, 起, 止, 名 = 打包模块.查阶段(0.15)
    assert 键 == "构建"
    序, 键, 起, 止, 名 = 打包模块.查阶段(0.999)
    assert 键 == "压缩" and 止 == 1.0
    序, 键, 起, 止, 名 = 打包模块.查阶段(1.0)
    assert 键 == "压缩"


def test_进入阶段段内映射(打包模块) -> None:
    态 = 打包模块.打包进度()
    起, 止 = 打包模块.阶段区间("构建")
    态.进入阶段("构建", "开始", 段内=0.0)
    assert abs(态.目标进度 - 起) < 1e-9
    态.进入阶段("构建", "中途", 段内=0.5, 明细="100 MB")
    assert abs(态.目标进度 - (起 + (止 - 起) * 0.5)) < 1e-9
    assert 态.明细 == "100 MB"
    态.完成阶段("构建", "完")
    assert abs(态.目标进度 - 止) < 1e-9


def test_进度单调不回退(打包模块) -> None:
    态 = 打包模块.打包进度()
    态.完成阶段("版本")
    态.完成阶段("依赖")
    高 = 态.目标进度
    # 试图回到依赖段首 — 必须被钳制
    态.进入阶段("依赖", "不该回退", 段内=0.0)
    assert 态.目标进度 >= 高
    态.更新(0.01, "更不该")
    assert 态.目标进度 >= 高


def test_快照七元组契约(打包模块) -> None:
    态 = 打包模块.打包进度()
    态.进入阶段("组装", "拷贝", 段内=0.2, 明细="10/50 文件", 计量当前=10, 计量总共=50)
    目标, 文案, 阶段, 明细, 结束, 成功, 原因 = 态.快照()
    assert 目标 > 0
    assert 文案 == "拷贝"
    assert 阶段 == "组装"
    assert 明细 == "10/50 文件"
    assert 结束 is False and 成功 is False and 原因 == ""


def test_标记成功写满进度与耗时(打包模块, tmp_path) -> None:
    态 = 打包模块.打包进度()
    态.打点开始()
    绿 = tmp_path / "g"
    包 = tmp_path / "p.zip"
    绿.mkdir()
    包.write_bytes(b"ab")
    态.标记成功(绿色根=绿, 归档=包, 大小兆=1.5)
    assert 态.已成功 and 态.已结束
    assert 态.目标进度 == 1.0
    assert 态.文案 == "搞定了!"
    assert "1.5" in 态.明细 or "MB" in 态.明细
    assert 态.耗时秒 >= 0.0


def test_标记失败不抬满进度(打包模块) -> None:
    态 = 打包模块.打包进度()
    态.进入阶段("构建", "中", 段内=0.3)
    前 = 态.目标进度
    态.标记失败("模拟失败")
    assert 态.已结束 and not 态.已成功
    assert 态.失败原因 == "模拟失败"
    assert 态.目标进度 == 前  # 失败不伪造 100%


def test_格式化耗时可读(打包模块) -> None:
    assert "秒" in 打包模块.格式化耗时(3.2)
    assert "分" in 打包模块.格式化耗时(125)
    assert "时" in 打包模块.格式化耗时(3700)
